// Builds app/_lib/stationLockers.ts from Seoul Metro's open data
// "서울교통공사_물품보관함 위치정보" (data.go.kr/data/15044234), saved as UTF-8 in data/.
// These are the T-Locker (또타라커) banks. Usage: npm run lockers:build
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "data/seoul-metro-lockers.csv";
const OUTPUT = "app/_lib/stationLockers.ts";
/** Quarter the CSV describes (from the data set title); the file itself has no date column. */
const DATA_DATE = "2026-09-30";

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (char === '"') {
        quoted = false;
      } else {
        field += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ",") {
      row.push(field);
      field = "";
    } else if (char === "\n" || char === "\r") {
      if (char === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += char;
    }
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const INSIDE_GATE = /게이트\s*내부|운임지역\s*내/;
const FLOOR = /(?:B\s*(\d)\s*층?|지하\s*(\d)\s*층|지상\s*(\d)\s*층|(?<![\d,~-])(\d)\s*층|(중층))/;

/** "잠실74~95" → { base: "잠실", slots: 22 }; "충정로B", "충정로(1~15)" and "언주역" are handled too. */
function parseName(raw) {
  const range = raw.match(/\(?(\d+)\s*~\s*(\d+)\)?$/);
  const slots = range ? Number(range[2]) - Number(range[1]) + 1 : null;
  const base = raw
    .replace(/\(?\d+\s*~\s*\d+\)?$/, "")
    .replace(/(?<=[가-힣])[AB]$/, "")
    .replace(/역$/, "")
    .trim();
  return { base, slots };
}

function parseDetail(raw) {
  let detail = raw.replace(/\s+/g, " ").trim();
  detail = detail.replace(/^[가-힣0-9]+역\s+/, "").replace(/\s+[가-힣0-9]+역$/, "");
  const match = detail.match(FLOOR);
  let floor = null;
  if (match) {
    const [, b, under, above, bare, middle] = match;
    floor = middle ? "중층" : b || under ? `B${b || under}` : `${above || bare}F`;
    detail = detail.replace(match[0], " ");
  }
  detail = detail
    .replace(/\(\s*\)/g, "")
    .replace(/\s+/g, " ")
    .replace(/^[\s,]+|[\s,]+$/g, "");
  return { floor, detail: detail || "대합실" };
}

const [header, ...body] = parseCsv(readFileSync(SOURCE, "utf8"));
const column = (name) => {
  const index = header.findIndex((cell) => cell.trim() === name);
  if (index < 0) throw new Error(`Missing column: ${name}`);
  return index;
};
const COLUMNS = { line: column("호선"), name: column("보관함명"), detail: column("상세위치") };

const lockers = {};
let rows = 0;

for (const cells of body) {
  const line = (cells[COLUMNS.line] ?? "").trim();
  const name = (cells[COLUMNS.name] ?? "").trim();
  if (!/^\d$/.test(line) || !name) continue;
  rows++;
  const { base, slots } = parseName(name);
  const { floor, detail } = parseDetail(cells[COLUMNS.detail] ?? "");
  const key = `${base}역`;
  const list = (lockers[key] ??= []);
  const entry = { line: `${line}호선`, floor, detail, slots, insideGate: INSIDE_GATE.test(cells[COLUMNS.detail] ?? "") };
  const same = list.find((item) => item.line === entry.line && item.floor === entry.floor && item.detail === entry.detail);
  if (same) {
    same.slots = same.slots !== null && slots !== null ? same.slots + slots : (same.slots ?? slots);
    same.insideGate ||= entry.insideGate;
  } else {
    list.push(entry);
  }
}

const sortedKeys = Object.keys(lockers).sort((a, b) => a.localeCompare(b, "ko"));
const lockerLines = sortedKeys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(lockers[key])},`);

writeFileSync(
  OUTPUT,
  `// Generated by scripts/build-station-lockers.mjs — edit the CSV in data/ and rerun \`npm run lockers:build\`.

export type StationLocker = {
  line: string;
  /** "B1", "2F" or "중층"; null when the source doesn't say. */
  floor: string | null;
  detail: string;
  /** Number of compartments, when the source lists the box range. */
  slots: number | null;
  insideGate: boolean;
};

export const LOCKER_DATA_DATE = ${JSON.stringify(DATA_DATE)};

/** Seoul Metro T-Locker (또타라커) banks, keyed by Korean station name with 역. */
export const STATION_LOCKERS: Record<string, readonly StationLocker[]> = {
${lockerLines.join("\n")}
};
`,
);

console.log(`Wrote ${OUTPUT}: ${sortedKeys.length} stations, ${rows} rows (data date ${DATA_DATE}).`);
