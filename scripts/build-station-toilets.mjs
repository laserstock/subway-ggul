// Builds app/_lib/stationToilets.ts from Seoul Metro's open data
// "서울교통공사_역사공중화장실정보" (data.go.kr/data/15044453), saved as UTF-8 in data/.
// Usage: npm run toilets:build
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "data/seoul-metro-toilets.csv";
const OUTPUT = "app/_lib/stationToilets.ts";

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (char === '"') {
        quoted = false;
      } else {
        field += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ",") {
      row.push(field);
      field = "";
    } else if (char === "\n" || char === "\r") {
      if (char === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += char;
    }
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

/** Toilets on the platform itself are always inside the fare gates, whatever the gate column says. */
const ON_PLATFORM = /승강장\s*\d|\d-\d\s*(지점|승강장)|승강장\s*앞/;

/** Floors the CSV gets wrong, checked against the station maps in public/station-maps. */
const FLOOR_FIXES = {
  "3호선 안국": "B2",
  "5호선 강일": "B1",
  "6호선 월드컵경기장": "B2",
};

function floorOf(row) {
  const fixed = FLOOR_FIXES[`${row.line} ${row.name}`];
  if (fixed) return fixed;
  const level = Number(row.level) || 1;
  return row.ground === "지상" ? `${level}F` : `B${level}`;
}

function cleanExit(raw) {
  const exit = raw.trim().replace(/\s*또는\s*/g, "·");
  return exit || null;
}

function cleanDetail(raw) {
  let detail = raw.trim();
  detail = detail.replace(/[[(]\s*게이트\s*(내|외|안|밖)\s*[\])]/g, "");
  detail = detail.replace(/,\s*게이트\s*(내|외|안|밖|밬)(?=$|[\s,)])/g, "");
  detail = detail.replace(/게이트\s*(내|안)\s+(?=대합실)/g, "");
  detail = detail.replace(/([가나다라]\)?)\s*게이트\s*(내부|외부|안쪽|밖|밬|안|외|내)(?=$|[\s,)])/g, "$1게이트");
  detail = detail.replace(/\s*게이트\s*(내부|외부|안쪽|밖|밬|안|외|내)(?=$|[\s,)])/g, "");
  detail = detail.replace(/\(\s*,\s*/g, "(");
  detail = detail.replace(/대합실\s*\d+\s*층/g, "대합실");
  detail = detail.replace(/(지하|지상)\s*\d+\s*층|B\d+\s*층?|^\d+층/g, "");
  detail = detail.replace(/\(\s*\)/g, "").replace(/\s+/g, " ");
  detail = detail.replace(/^[\s,]+|[\s,]+$/g, "");
  if (/^\(.*\)$/.test(detail)) detail = detail.slice(1, -1).trim();
  return detail || "대합실";
}

const [header, ...body] = parseCsv(readFileSync(SOURCE, "utf8"));
const column = (name) => {
  const index = header.findIndex((cell) => cell.trim() === name);
  if (index < 0) throw new Error(`Missing column: ${name}`);
  return index;
};
const COLUMNS = {
  line: column("운영노선명"),
  name: column("역명"),
  road: column("소재지도로명주소"),
  lot: column("소재지지번주소"),
  ground: column("지상 또는 지하 구분"),
  level: column("역층"),
  gate: column("게이트 내외 구분"),
  exit: column("(근접) 출입구 번호"),
  detail: column("상세위치"),
  date: column("데이터기준일자"),
};

const toilets = {};
const addresses = {};
let dataDate = "";

for (const cells of body) {
  const row = Object.fromEntries(Object.entries(COLUMNS).map(([key, index]) => [key, (cells[index] ?? "").trim()]));
  if (!row.name || !row.line) continue;
  const key = `${row.name.replace(/역$/, "")}역`;
  dataDate ||= row.date;
  const gate = row.gate === "내부" || ON_PLATFORM.test(row.detail) ? "inside" : "outside";
  (toilets[key] ??= []).push({
    line: row.line,
    floor: floorOf(row),
    gate,
    exit: cleanExit(row.exit),
    detail: cleanDetail(row.detail),
  });
  const known = (addresses[key] ??= { road: [], lot: [] });
  if (row.road && !known.road.includes(row.road)) known.road.push(row.road);
  if (row.lot && !known.lot.includes(row.lot)) known.lot.push(row.lot);
}

const sortedKeys = Object.keys(toilets).sort((a, b) => a.localeCompare(b, "ko"));
const toiletLines = sortedKeys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(toilets[key])},`);
const addressLines = sortedKeys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(addresses[key])},`);

writeFileSync(
  OUTPUT,
  `// Generated by scripts/build-station-toilets.mjs — edit the CSV in data/ and rerun \`npm run toilets:build\`.

export type StationToilet = {
  line: string;
  floor: string;
  gate: "inside" | "outside";
  exit: string | null;
  detail: string;
};

export const TOILET_DATA_DATE = ${JSON.stringify(dataDate)};

/** Seoul Metro station toilets (Lines 1–8), keyed by Korean station name with 역. */
export const STATION_TOILETS: Record<string, readonly StationToilet[]> = {
${toiletLines.join("\n")}
};

/** Road and lot addresses of each station building, used to spot in-station shops. */
export const STATION_ADDRESSES: Record<string, { road: readonly string[]; lot: readonly string[] }> = {
${addressLines.join("\n")}
};
`,
);

console.log(`Wrote ${OUTPUT}: ${sortedKeys.length} stations, ${body.length} rows (data date ${dataDate}).`);
